type TextKey = keyof typeof vietnamese
type Values = Record<string, string | number>

export function catanTranslator(language: CatanLanguage) {
  return (key: TextKey, values: Values = {}) =>
    (language === 'vi' ? vietnamese[key] : key).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}

// Engine messages stay in English so switching languages also translates past events.
const dynamicMessages: readonly TextKey[] = [
  '{name} built a ship.', '{name} relocated a ship.', '{name} moved the pirate.',
  '{name} wins with {points} points!',
  '{resource} shortage: no production of that resource this roll.',
  '{name} built a settlement.', '{name} built a road.',
  '{name} upgraded a settlement to a city.', '{name} rolled {first} + {second} = {total}.',
  '{name} discarded half their resources.', '{name} moved the robber.',
  '{name} stole one hidden resource from {other}.',
  '{name} traded {count} {give} for 1 {receive} with the bank.',
  '{name} offered a trade to {other}.', '{name} accepted the trade.', '{name} declined the trade.',
  '{name} bought a hidden development card.', '{name} played {card}.', "{name}'s turn.",
  'The bank does not have enough {resource}.', 'This trade needs {count} {resource}.',
]
const messagePatterns = dynamicMessages.map(key => {
  const fields: string[] = []
  const pattern = key.split(/(\{\w+\})/).map(part => {
    if (part.startsWith('{')) {
      fields.push(part.slice(1, -1))
      return '(.+)'
    }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  }).join('')
  return { key, fields, pattern: new RegExp(`^${pattern}$`, 'su') }
})
const termKeys: Record<string, TextKey> = {
  wood: 'Wood', brick: 'Brick', wool: 'Wool', grain: 'Grain', ore: 'Ore',
  Wood: 'Wood', Brick: 'Brick', Wool: 'Wool', Grain: 'Grain', Ore: 'Ore',
  Knight: 'Knight', 'Victory point': 'Victory point', 'Road building': 'Road building',
  'Year of plenty': 'Year of plenty', Monopoly: 'Monopoly',
}

export function localizeCatanMessage(language: CatanLanguage, message: string): string {
  if (language === 'en') return message
  const t = catanTranslator(language)
  if (Object.hasOwn(vietnamese, message)) return t(message as TextKey)
  for (const { key, fields, pattern } of messagePatterns) {
    const match = pattern.exec(message)
    if (!match) continue
    const values: Values = {}
    fields.forEach((field, index) => {
      const value = match[index + 1]
      values[field] = ['resource', 'give', 'receive', 'card'].includes(field) && Object.hasOwn(termKeys, value) ? t(termKeys[value]) : value
    })
    return t(key, values)
  }
  return message
}
